function makeCollector() {
  const findings = [];
  const seen = new Set();
  const add = (f) => {
    const key = `${f.id}|${f.file || ""}|${f.line || ""}|${f.message}`;
    if (seen.has(key)) return;
    seen.add(key);
    findings.push({
      id: f.id,
      pillar: f.pillar,
      severity: f.severity,
      evidence: f.evidence || "high",
      confidence: f.confidence || "likely",
      file: f.file || null,
      line: f.line || null,
      message: f.message,
      fix: f.fix || null,
      ref: f.ref || null,
      cluster: f.cluster || f.file || f.id,
    });
  };
  return { findings, add };
}

