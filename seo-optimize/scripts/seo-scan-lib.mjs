function siblingSources(p, file) {
  const dir = path.posix.dirname(file);
  return p.files.filter((f) => path.posix.dirname(f) === dir && f !== file && /\.(tsx|jsx|ts|js|svelte)$/.test(f)).map((f) => p.src(f) || "");
}

